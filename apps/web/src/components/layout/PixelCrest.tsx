function crestInitial(raw: string): string {
  const clean = raw.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase();
  const char = clean.charAt(0);
  return FONT[char] ? char : 'M';
}

type Cell = { x: number; y: number; fill: string };

function buildCells(letter: string): Cell[] {
  const inside: boolean[][] = Array.from({ length: H }, () => Array(W).fill(false));
  for (let y = 0; y < H; y += 1) {
    const half = HALF[y] ?? 0;
    for (let x = 0; x < W; x += 1) {
      if (Math.abs(x - 12.5) <= half) inside[y][x] = true;
    }
  }

  const dist: number[][] = Array.from({ length: H }, () => Array(W).fill(99));
  for (let y = 0; y < H; y += 1) {
    for (let x = 0; x < W; x += 1) {
      if (!inside[y][x]) continue;
      let nearest = 99;
      for (let ny = 0; ny < H; ny += 1) {
        for (let nx = 0; nx < W; nx += 1) {
          if (inside[ny][nx]) continue;
          const d = Math.max(Math.abs(nx - x), Math.abs(ny - y));
          if (d < nearest) nearest = d;
        }
      }
      dist[y][x] = nearest;
    }
  }

  const cells: Cell[] = [];
  for (let y = 0; y < H; y += 1) {
    for (let x = 0; x < W; x += 1) {
      if (!inside[y][x]) continue;
      const d = dist[y][x];
      let fill = '#141418';
      if (d <= 1) fill = '#111111';
      else if (d === 2) fill = '#f0c828';
      else if (d === 3) fill = '#c89818';
      cells.push({ x, y, fill });
    }
  }

  const glyph = FONT[letter] ?? FONT.M;
  const ox = 10;
  const oy = 8;
  glyph.forEach((row, gy) => {
    for (let gx = 0; gx < row.length; gx += 1) {
      if (row[gx] !== '1') continue;
      const x = ox + gx;
      const y = oy + gy;
      const cell = cells.find((item) => item.x === x && item.y === y);
      if (cell && dist[y][x] >= 4) cell.fill = '#f7f4ea';
    }
  });

  return cells;
}

export function PixelCrest({
  letter,
  size = 52,
}: {
  letter: string;
  size?: number;
}) {
  const initial = crestInitial(letter);
  const cells = useMemo(() => buildCells(initial), [initial]);
  const height = Math.round(size * (H / W));

  return (
    <svg
      viewBox={`0 0 ${W} ${H}`}
      width={size}
      height={height}
      className="pixel-sprite"
      shapeRendering="crispEdges"
      role="img"
      aria-label={initial}
    >
      {cells.map((cell) => (
        <rect key={`${cell.x}-${cell.y}`} x={cell.x} y={cell.y} width="1" height="1" fill={cell.fill} />
      ))}
    </svg>
  );
}
