export type ErrorCodeType = (typeof ErrorCode)[keyof typeof ErrorCode];

export interface SerializedError {
  error: {
    code: ErrorCodeType;
    statusCode: number;
    details?: Record<string, unknown>;
  };
}

export function serializeError(
  code: ErrorCodeType,
  statusCode: number,
  details?: Record<string, unknown>,
): SerializedError {
  return {
    error: {
      code,
      statusCode,
      ...(details ? { details } : {}),
    },
  };
}
